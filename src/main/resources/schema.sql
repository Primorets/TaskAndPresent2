CREATE TABLE IF NOT EXISTS USERS
(
    ID    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME  VARCHAR(255)                            NOT NULL,
    EMAIL VARCHAR(512)                            NOT NULL,
    CONSTRAINT PK_USER PRIMARY KEY (ID),
    CONSTRAINT UQ_USER_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE IF NOT EXISTS PURCHASES
(
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME             VARCHAR(2500)                           NOT NULL,
    STATUS_PURCHASES VARCHAR(500)                            NOT NULL,
    IS_CONSUMABLE    BOOLEAN                                 NOT NULL,
    DIMENSION        VARCHAR(500),
    QUANTITY         BIGINT,
    CONSTRAINT PK_PURCHASE PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS EVENTS
(
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME           VARCHAR(255)                            NOT NULL,
    DESCRIPTION    VARCHAR(500)                            NOT NULL,
    STATUS_EVENT   VARCHAR(500)                            NOT NULL,
    START_DATE     TIMESTAMP,
    END_DATE       TIMESTAMP,

    CONSTRAINT PK_EVENT PRIMARY KEY (ID)
);


//ПРОМЕЖУТОЧНАЯ ТАБЛИЦА ДЛЯ СВЯЗИ ПОЛЬЗОВАТЕЛЕЙ И ПОКУПОК:
CREATE TABLE IF NOT EXISTS USER_PURCHASES
(
    USER_ID     BIGINT NOT NULL,
    PURCHASE_ID BIGINT NOT NULL,
    CONSTRAINT PK_USER_PURCHASES PRIMARY KEY (USER_ID, PURCHASE_ID),
    CONSTRAINT FK_USER_PURCHASES_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_USER_PURCHASES_PURCHASE_ID FOREIGN KEY (PURCHASE_ID) REFERENCES PURCHASES (ID) ON DELETE CASCADE
);

//ПРОМЕЖУТОЧНАЯ ТАБЛИЦА ДЛЯ СВЯЗИ СОБЫТИЙ И УЧАСТНИКОВ:
CREATE TABLE IF NOT EXISTS EVENT_PARTICIPANTS
(
    EVENT_ID       BIGINT NOT NULL,
    PARTICIPANT_ID BIGINT NOT NULL,
    CONSTRAINT PK_EVENT_PARTICIPANTS PRIMARY KEY (EVENT_ID, PARTICIPANT_ID),
    CONSTRAINT FK_EVENT_PARTICIPANTS_EVENT_ID FOREIGN KEY (EVENT_ID) REFERENCES EVENTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_EVENT_PARTICIPANTS_PARTICIPANT_ID FOREIGN KEY (PARTICIPANT_ID) REFERENCES USERS (ID) ON DELETE CASCADE
);
